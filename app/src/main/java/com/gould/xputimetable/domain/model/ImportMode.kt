/*
 * ImportMode.kt —— 导入入库方式（M7 需求 1）
 *
 * 用户在导入预览页二选一，决定 applyImport 如何对待「库里已有的课表」：
 *
 * REPLACE（覆盖原课表，默认）
 *   先清掉当前学期**全部非手动**来源的课程，再写入本次内容。
 *   语义：课表变成「本次导入的内容 + 手动添加的课程」。
 *   为什么不是"只清同来源"：用户选「覆盖」的含义就是"课表变成这份内容"；若只清同来源，
 *   别的通道导入的课程会留下来，与本次内容同名并列——这正是"同课重复"的来源
 *   （真机实测：教务导入 9 门 + 文件导入 9 门，内容完全相同却各占一份）。
 *   安全不变量不变：MANUAL 来源的课程永不删除（代码层拒绝 + DAO 层 SQL 兜底，AC-20）。
 *
 * APPEND（插入原课表）
 *   不清任何东西，把本次课程追加进现有课表。
 *   语义：课表变成「原有内容 + 本次导入的内容」（例如先导了一批、再补几门）。
 *   已知代价：重复导入会产生重复课程（同名课程在周视图上并列显示），
 *   预览页会就此给出明确提示，由用户自行决定。
 */
package com.gould.xputimetable.domain.model

enum class ImportMode {
    /** 覆盖：清掉同来源旧课程后写入（默认）。 */
    REPLACE,

    /** 插入：保留现有课表，本次课程追加写入。 */
    APPEND,
}
